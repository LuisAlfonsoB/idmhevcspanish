const LANGS = { en: { name: 'English' }, es: { name: 'Español', dict: ES, pats: ES_PATTERNS } };

/** 'auto' | 'en' | 'es' (+ the OS locale) -> a supported language code. */
function resolve(setting, locale) {
  const s = String(setting || 'auto').toLowerCase();
  if (LANGS[s]) return s;
  const l = String(locale || '').toLowerCase().split(/[-_]/)[0];
  return LANGS[l] ? l : 'en';
}

// ---- translate(): the same algorithm lives in ui/i18n-dom.js and pages/shared/i18n-dom.js; keep the three in sync ----
function compile(pats) { return (pats || []).map(([src, tpl]) => [new RegExp(src), tpl]); }
function one(c, D) {
  if (Object.prototype.hasOwnProperty.call(D.dict, c)) return D.dict[c];
  for (const [re, tpl] of D.pats) if (re.test(c)) return c.replace(re, tpl);
  if (c.startsWith('✓ ')) { const r = one(c.slice(2), D); if (r !== c.slice(2)) return '✓ ' + r; }
  if (c.indexOf(' · ') > 0) {
    const parts = c.split(' · '); let changed = false;
    const out = parts.map(p => { const r = one(p, D); if (r !== p) changed = true; return r; });
    if (changed) return out.join(' · ');
  }
  return c;
}
function translate(s, D) {
  if (!D || typeof s !== 'string' || !s) return s;
  const m = /^(\s*)([\s\S]*?)(\s*)$/.exec(s);
  if (!m[2]) return s;
  const r = one(m[2], D);
  return r === m[2] ? s : m[1] + r + m[3];
}

let current = { lang: 'en', D: null };
function setLanguage(lang) {
  const l = LANGS[lang] && LANGS[lang].dict ? lang : 'en';
  current = { lang: l, D: l === 'en' ? null : { dict: LANGS[l].dict, pats: compile(LANGS[l].pats) } };
  return current.lang;
}
/** Main-process translation: L('Back') -> 'Atrás' (or the same text in English / when unknown). */
const L = s => (current.D ? translate(s, current.D) : s);
/** What a renderer's preload needs (plain data, safe to send over IPC). */
function payload() { return current.D ? { lang: current.lang, dict: current.D.dict, pats: LANGS[current.lang].pats } : { lang: 'en', dict: null, pats: [] }; }
const language = () => current.lang;
const languages = () => Object.entries(LANGS).map(([code, v]) => ({ code, name: v.name }));

module.exports = { resolve, setLanguage, language, languages, payload, L, translate, compile };
